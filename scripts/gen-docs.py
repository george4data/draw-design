#!/usr/bin/env python3
"""Regenerate generated documentation blocks from data (or --check that they are current).

Sources of truth: data/types.d/*.json, data/budgets.json, data/presets.json, themes/default.json.
Targets: SKILL.md (types table), references/style-guide.md, references/layout-budget.md,
.codex-plugin/plugin.json (longDescription type list).
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SKILL = ROOT / "skills" / "draw-design"
sys.path.insert(0, str(SKILL / "scripts"))

from ddraw import registry  # noqa: E402
from ddraw.theme.contrast import report  # noqa: E402
from ddraw.theme.model import ROLES, load_theme  # noqa: E402


def block(text: str, name: str, body: str) -> str:
    pat = re.compile(rf"(<!-- BEGIN GENERATED:{name} -->\n).*?(<!-- END GENERATED:{name} -->)", re.S)
    if not pat.search(text):
        raise SystemExit(f"missing GENERATED:{name} markers")
    return pat.sub(lambda m: m.group(1) + body + m.group(2), text)


def types_table() -> str:
    rows = ["| If you're showing… | Use `type` | Reference |", "|---|---|---|"]
    for t in registry.shipped():
        rows.append(f"| {t.use_when} | `{t.slug}` | [type-{t.slug}.md](references/type-{t.slug}.md) |")
    return "\n".join(rows) + "\n"


def style_guide() -> str:
    theme = load_theme()
    raw = theme.raw
    lines = [
        "# Style guide (default theme)",
        "",
        "<!-- Generated by scripts/gen-docs.py from themes/default.json. Do not edit by hand. -->",
        "",
        "Diagrams name colours by **semantic role**; the compiler binds roles to the active theme and emits",
        "each colour as `light-dark(<light>,<dark>)` so a file follows draw.io's light and dark modes.",
        "",
        "| Role | Light | Dark |",
        "|---|---|---|",
    ]
    lines += [f"| `{r}` | `{raw['light'][r]}` | `{raw['dark'][r]}` |" for r in ROLES]
    lines += ["", "## Typography", "", "| Role | Family stack |", "|---|---|"]
    lines += [f"| `{k}` | {v['stack']} |" for k, v in raw["fonts"].items()]
    lines += ["", "## Contrast (WCAG, against paper)", "", "| Skin | Role | Ratio |", "|---|---|---|"]
    lines += [f"| {s} | `{r}` | {x:.2f}:1 |" for s, r, x in report(theme)]
    lines += [
        "",
        "## Node treatments",
        "",
        "| Treatment | Fill | Stroke |",
        "|---|---|---|",
        "| `focal` (≤ 2) | accent @ 0.08 | accent, 1.2 |",
        "| `backend` | nodeFill | ink |",
        "| `store` | ink @ 0.05 | muted |",
        "| `external` | ink @ 0.03 | ink @ 0.30 |",
        "| `input` | muted @ 0.10 | soft |",
        "| `optional` | ink @ 0.02 | ink @ 0.20, dashed 4 3 |",
        "| `security` | accent @ 0.05 | accent @ 0.50, dashed 4 4 |",
        "",
    ]
    return "\n".join(lines)


def layout_budget() -> str:
    b = registry.budgets()
    p = registry.presets()
    lines = [
        "# Layout budget",
        "",
        "<!-- Generated by scripts/gen-docs.py from data/. Do not edit by hand. -->",
        "",
        "## Universal limits",
        "",
        "| Limit | Value |",
        "|---|---|",
    ]
    lines += [f"| {k} | {v} |" for k, v in b["universal"].items()]
    lines += ["", "## Detail levels", "", "| Detail | Nodes | Edges |", "|---|---|---|"]
    lines += [f"| `{k}` | {v['nodes']} | {v['edges']} |" for k, v in b["detail"].items()]
    lines += ["", "## Size presets", "", "| Preset | Frame | Type ramp |", "|---|---|---|"]
    for k, v in p["presets"].items():
        frame = "content + margins" if k == "fit" else f"{v['width']}×{v['height']}"
        lines.append(f"| `{k}` | {frame} | {v['ramp']} |")
    lines += ["", "## Per-type budgets", "", "| Type | Status | Budget |", "|---|---|---|"]
    for t in sorted(registry.types().values(), key=lambda t: (t.wave, t.slug)):
        budget = ", ".join(f"{k} {v}" for k, v in t.budget.items()) or "universal"
        lines.append(f"| `{t.slug}` | {t.status} | {budget} |")
    return "\n".join(lines) + "\n"


def codex_long(manifest: dict[str, object]) -> str:
    iface = manifest["interface"]
    assert isinstance(iface, dict)
    text = str(iface["longDescription"])
    names = ", ".join(t.slug for t in registry.shipped())
    return re.sub(r"Shipped diagram types: [^\n]*\.", f"Shipped diagram types: {names}.", text)


def main() -> int:
    check = "--check" in sys.argv
    targets: dict[Path, str] = {}
    skill_md = SKILL / "SKILL.md"
    targets[skill_md] = block(skill_md.read_text(encoding="utf-8"), "types", types_table())
    targets[SKILL / "references" / "style-guide.md"] = style_guide()
    targets[SKILL / "references" / "layout-budget.md"] = layout_budget()
    codex = ROOT / ".codex-plugin" / "plugin.json"
    manifest = json.loads(codex.read_text(encoding="utf-8"))
    manifest["interface"]["longDescription"] = codex_long(manifest)
    targets[codex] = json.dumps(manifest, indent=2, ensure_ascii=False) + "\n"
    stale = []
    for path, text in targets.items():
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if current != text:
            stale.append(path.relative_to(ROOT))
            if not check:
                path.write_text(text, encoding="utf-8")
    if check and stale:
        print("stale generated files (run: python scripts/gen-docs.py):", *stale, sep="\n  ")
        return 1
    print("generated docs are current" if check else f"updated {len(stale)} file(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
